"""Generate benchmark datasets for FigTreeKit evaluation.

Creates 3 synthetic phylogenetic trees with anonymous taxon codes:
1. mammalian_mitogenome.tre — 30 taxa (M0001–M0030)
2. hiv_env.tre                — 100 taxa (H0001–H0100)
3. rrna_16s.tre               — 500 taxa (B0001–B0500)

The trees are generated by a neutral Yule process and are intended solely for
performance benchmarking.  Tip labels are letter-plus-number codes rather than
real organism names.
"""

import random
from pathlib import Path

random.seed(42)


def _generate_codes(prefix: str, count: int) -> list:
    """Generate anonymous taxon codes like M0001, H0100, B0500."""
    width = max(4, len(str(count)))
    return [f"{prefix}{i:0{width}d}" for i in range(1, count + 1)]


def generate_random_tree(taxa: list, branch_scale: float = 0.01) -> str:
    """Generate a random ultrametric Newick tree using a Yule process."""
    nodes = list(taxa)
    while len(nodes) > 1:
        # Pick two random nodes to join
        i, j = random.sample(range(len(nodes)), 2)
        node_a = nodes[i]
        node_b = nodes[j]
        # Random branch length
        bl_a = round(random.expovariate(1.0 / branch_scale), 6)
        bl_b = round(random.expovariate(1.0 / branch_scale), 6)
        # Create parent node
        parent = f"({node_a}:{bl_a},{node_b}:{bl_b})"
        # Remove old nodes, add parent
        remaining = [n for k, n in enumerate(nodes) if k not in (i, j)]
        remaining.append(parent)
        nodes = remaining
    return nodes[0] + ";"


def generate_mammalian_mitogenome() -> str:
    """30 taxa with anonymous mammal-like benchmark codes."""
    taxa = _generate_codes("M", 30)
    return generate_random_tree(taxa, branch_scale=0.01)


def generate_hiv_env() -> str:
    """100 taxa with anonymous viral benchmark codes."""
    taxa = _generate_codes("H", 100)
    return generate_random_tree(taxa, branch_scale=0.005)


def generate_rrna_16s() -> str:
    """500 taxa with anonymous bacterial benchmark codes."""
    taxa = _generate_codes("B", 500)
    return generate_random_tree(taxa, branch_scale=0.01)


def main():
    out_dir = Path(__file__).parent

    datasets = [
        ("mammalian_mitogenome.tre", generate_mammalian_mitogenome, 30),
        ("hiv_env.tre", generate_hiv_env, 100),
        ("rrna_16s.tre", generate_rrna_16s, 500),
    ]

    for filename, generator, expected_count in datasets:
        print(f"Generating {filename} (~{expected_count} taxa)...")
        tree = generator()
        out_path = out_dir / filename
        out_path.write_text(tree)
        # Count taxa
        leaf_count = tree.count(",") + 1
        print(f"  Written: {out_path} ({leaf_count} taxa, {len(tree)} bytes)")

    print("\nDone. All datasets generated.")


if __name__ == "__main__":
    main()
